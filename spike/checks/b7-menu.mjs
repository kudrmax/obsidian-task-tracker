import { connect, sleep, click, key } from "./cdp.mjs";
import { rectOf } from "./rect.mjs";
const c = await connect();
const open = () => c.evaluate(`!!document.querySelector(".tcs-menu")`);
const btn = await rectOf(c, ".tcs-menu-button");
const out = {};
await click(c, btn); await sleep(300); out.openedByClick = await open();
out.menuBox = await rectOf(c, ".tcs-menu"); out.inSameDocAsView = await c.evaluate(`document.querySelector(".tcs-menu")?.ownerDocument === document.querySelector(".tcs-screen").ownerDocument`);
await c.shot((process.argv[3] ?? "") + "b7-menu-open");
await key(c, "Escape", "Escape", 27); await sleep(300); out.closedByEscape = !(await open());
await click(c, btn); await sleep(300); out.reopened = await open();
await click(c, { x: btn.x + 600, y: btn.y + 400 }); await sleep(300); out.closedByOutsideClick = !(await open());
await click(c, btn); await sleep(300);
const first = await c.evaluate(`tcSpike.store.getState().columns.inbox[0]`);
const item = await rectOf(c, ".tcs-menu button");
await click(c, item); await sleep(1200);
out.itemRan = (await c.evaluate(`tcSpike.store.getState().columns.soon[0]`)) === first;
out.closedAfterItem = !(await open());
console.log(JSON.stringify(out));
c.close();
