import { connect, mouseDrag, SAMPLER, sleep } from "./cdp.mjs";
import { rectOf } from "./rect.mjs";
import { writeFileSync } from "node:fs";
const c = await connect();
await c.evaluate(SAMPLER);
const st = (e) => c.evaluate(`(() => { const s = tcSpike.store.getState(); return ${e}; })()`);
const inbox = await st(`s.columns.inbox.slice(0, 3)`), soon = await st(`s.columns.soon.slice(0, 5)`);
const watch = [inbox[0], inbox[1], soon[2], soon[3]];
const a = await rectOf(c, `[data-id="${inbox[0]}"]`), b = await rectOf(c, `[data-id="${soon[2]}"]`);
await c.evaluate(`window.__stop = __sample(${JSON.stringify(watch)})`);
await mouseDrag(c, a, { x: b.x, y: b.top + 4 }, { steps: 30 });
await sleep(1000);
const samples = await c.evaluate(`window.__stop()`);
const after = await st(`({ inbox: s.columns.inbox.slice(0, 3), soon: s.columns.soon.slice(0, 5), title: s.faces["${inbox[0]}"].title, reads: s.reads, write: s.lastWriteMs })`);
const file = await c.evaluate(`app.vault.adapter.read("TODOs Tasks.md").then(t => { const l = t.split("\\n"); const i = l.indexOf("## Soon"); return l.slice(i, i + 5).join("\\n"); })`);
writeFileSync(new URL("../shots/b1-cross.json", import.meta.url), JSON.stringify({ watch, before: { inbox, soon }, after, file, samples }, null, 1));
console.log(JSON.stringify({ before: { inbox, soon }, after, file }, null, 1));
await c.shot("b1-cross-after");
c.close();
